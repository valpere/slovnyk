// Package downloads resolves published, immutable exports without accepting paths.
package downloads

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/valpere/slovnyk/internal/artifacts"
	"github.com/valpere/slovnyk/internal/catalog"
	"github.com/valpere/slovnyk/internal/lookup"
	"github.com/valpere/slovnyk/internal/publication"
)

var ErrNotFound = errors.New("export_not_found")

type Export struct {
	Dataset, ID, From, To string
	Rows                  int64
	Artifact              artifacts.Ref
}
type Manifest struct {
	Dataset string
	Exports []Export
}

const columns = `e.dataset_id::text,e.export_id::text,e.source_locale,e.target_locale,e.logical_rows,e.artifact_path,encode(e.sha256,'hex'),e.byte_size`
const published = ` FROM slovnyk.exports e JOIN slovnyk.datasets d ON d.id=e.dataset_id
 WHERE d.state='ready' AND e.verified AND EXISTS(SELECT 1 FROM slovnyk.publication_events WHERE new_dataset_id=d.id)`

func scan(row pgx.Row) (Export, error) {
	var e Export
	err := row.Scan(&e.Dataset, &e.ID, &e.From, &e.To, &e.Rows, &e.Artifact.Path, &e.Artifact.SHA256, &e.Artifact.Bytes)
	if err != nil {
		return Export{}, err
	}
	// Only references generated by publication may reach the confined store.
	want := fmt.Sprintf("datasets/%s/exports/%s/%s.csv.gz", e.Dataset, e.ID, e.Artifact.SHA256)
	if !publication.ValidID(e.Dataset) || !publication.ValidID(e.ID) || e.Artifact.Path != want || len(e.Artifact.SHA256) != 64 || e.Artifact.Bytes <= 0 || e.Rows < 0 {
		return Export{}, lookup.ErrUnavailable
	}
	return e, nil
}

// List pins the active pointer once; the ready dataset is immutable thereafter.
// It borrows c, and never reads artifact contents or regenerates exports.
func List(ctx context.Context, c *pgx.Conn) (Manifest, error) {
	var m Manifest
	if err := c.QueryRow(ctx, `SELECT coalesce(dataset_id::text,'') FROM slovnyk.active_dataset WHERE singleton=1`).Scan(&m.Dataset); err != nil || m.Dataset == "" {
		return Manifest{}, lookup.ErrUnavailable
	}
	// Catalog validity and bounds are checked before exposing the manifest.
	inventory, err := catalog.Read(ctx, c, m.Dataset)
	if err != nil {
		return Manifest{}, lookup.ErrUnavailable
	}
	rows, err := c.Query(ctx, `SELECT `+columns+published+` AND e.dataset_id=$1 ORDER BY e.source_locale COLLATE "C",e.target_locale COLLATE "C" LIMIT $2`, m.Dataset, catalog.MaxPairs+1)
	if err != nil {
		return Manifest{}, lookup.ErrUnavailable
	}
	defer rows.Close()
	for rows.Next() {
		e, err := scan(rows)
		if err != nil {
			return Manifest{}, lookup.ErrUnavailable
		}
		m.Exports = append(m.Exports, e)
	}
	if rows.Err() != nil || ctx.Err() != nil || len(m.Exports) > catalog.MaxPairs || len(m.Exports) != len(inventory.Pairs) {
		return Manifest{}, lookup.ErrUnavailable
	}
	return m, nil
}

// Resolve uses the supplied dataset pin, including published retained versions.
// A ready but never published dataset is not publicly downloadable.
func Resolve(ctx context.Context, c *pgx.Conn, dataset, id string) (Export, error) {
	if !publication.ValidID(dataset) || !publication.ValidID(id) {
		return Export{}, ErrNotFound
	}
	e, err := scan(c.QueryRow(ctx, `SELECT `+columns+published+` AND e.dataset_id=$1 AND e.export_id=$2`, dataset, id))
	if errors.Is(err, pgx.ErrNoRows) {
		return Export{}, ErrNotFound
	}
	if err != nil || ctx.Err() != nil {
		return Export{}, lookup.ErrUnavailable
	}
	return e, nil
}
